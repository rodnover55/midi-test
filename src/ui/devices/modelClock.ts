/**
 * Часы, по которым изображения устройств вычисляют то, что меняется между
 * сообщениями: мигание темпа, ход лупера, закрытие окон по таймауту.
 */

import { createContext, useContext } from 'react';

/**
 * Возвращает текущий момент модели — миллисекунды Unix-времени в той же
 * шкале, что и моменты в состоянии устройства.
 */
export type ModelClock = () => number;

/**
 * Часы модели для изображений устройств. По умолчанию — часы страницы
 * (Date.now): состояние приходит от монитора в реальном времени. Страница,
 * которая показывает состояние в другой шкале времени (например, прогон
 * сообщений с условного момента), задаёт свои часы через Provider; значение
 * должно оставаться тем же объектом, пока шкала не сменилась.
 */
export const ModelClockContext = createContext<ModelClock>(Date.now);

/** Возвращает часы модели из ближайшего {@link ModelClockContext}. */
export function useModelClock(): ModelClock {
  return useContext(ModelClockContext);
}
